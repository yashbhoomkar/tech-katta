// Writes src/features/workspace/legacy-scope.css: the current app's design tokens (frontend/src/theme/tokens.css)
// scoped to `.tk-legacy` instead of :root, so its workspace (canvas, judge, panes) can run inside this app without
// its tokens leaking out. Colours and fonts are then overridden to this design (figureTokens + the font block
// below). Run after tokens.css changes: node scripts/legacy-scope.mjs
import { readFileSync, writeFileSync } from "node:fs";

const src = readFileSync(new URL("../../src/theme/tokens.css", import.meta.url), "utf8");
const body = src.slice(src.indexOf(":root{"))
  .replace(/^:root\{/m, ".tk-legacy{")
  .replace(/\.on-dark,:root\[data-theme=dark\]\{/, ":root[data-theme=dark] .tk-legacy{");
const out = `/* GENERATED by scripts/legacy-scope.mjs from frontend/src/theme/tokens.css. Do not edit. */\n${body}\n`;
writeFileSync(new URL("../src/features/workspace/legacy-scope.css", import.meta.url), out);
console.log("legacy-scope.css written");
