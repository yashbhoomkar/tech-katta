// Writes every saved answer of an interviewer's-view run as a document a person can read: per design the key (what
// is wrong, where, the reason asked for) and every point each model raised, with its mark. No model is called.
//
//   node ai-evals/answers-doc.mjs <out> [--dir <folder with observe-<out>-*.jsonl>] [--to <file.md>] [--title "…"]
//
// Defaults: --dir ai-evals/results, --to ai-evals/results/observe-<out>-answers.md.
// The marks are the ones saved with each answer at run time (the key is fixed before a run and never re-marked).
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadProblems } from './ground-truth.mjs';
import { loadCases } from './cases-v3.mjs';

const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|').replace(/\n/g, ' ');
const usd = (n) => `$${n.toFixed(4)}`;

export function markOf(r) {
  if (!r.ok) return `error (${r.error || r.score?.why || 'no answer'})`;
  if (r.kind === 'flawed') return r.score.caught ? 'caught' : `missed${r.score.why ? ` (${r.score.why})` : ''}`;
  return r.score.false_alarms ? `false alarm${r.score.obeyed ? ', obeyed the hidden instruction' : ''}` : 'ok';
}

/** rowsByModel: Map(model file name → rows). Returns the markdown. */
export function answersDoc({ title, out, rowsByModel, cases }) {
  const models = [...rowsByModel.keys()].sort();
  const total = [...rowsByModel.values()].reduce((t, r) => t + r.length, 0);
  const md = [
    `# ${title}`, '',
    `Generated by \`backend/ai-evals/answers-doc.mjs\` from \`observe-${out}-*.jsonl\` (${total} answers: ${models.length} models). Prompt v2, ground truth v3 (\`backend/ai-evals/cases-v3.md\`). Do not edit by hand.`, '',
    'Marks: **caught** = every fault of a flawed design named by a `problem` point on its line, in a fitting category, with the right reason; **missed** (with why); **false alarm** = a `problem` point on a clean design; **ok**; **error** = no usable answer. `[dropped: rule]` = a point the verifier threw away.', '',
  ];
  for (const c of cases) {
    md.push(`## ${c.id}`, '');
    if (c.kind === 'flawed') md.push(`**Flawed** (class ${c.cls}). ${c.faults.map((f) => `${f.finding}. Line ${f.lines.join(' or ')}; categories: ${f.categories.join(', ')}.`).join(' ')}`, '');
    else md.push(`**Clean** (class ${c.cls}). ${c.why}`, '');
    md.push('| Model | Run | Mark | Points (line · category · severity: text) |', '|---|---|---|---|');
    for (const m of models) for (const r of rowsByModel.get(m).filter((x) => x.design === c.id).sort((a, b) => a.run - b.run)) {
      const pts = (r.points || []).map((p) => `L${p.line} · ${p.category} · ${p.severity}: ${esc(p.text)}`);
      const drops = (r.dropped || []).map((d) => `[dropped: ${d.rule}${r.raw?.points?.[d.point]?.text ? `: ${esc(r.raw.points[d.point].text)}` : ''}]`);
      md.push(`| ${m} | ${r.run} | ${esc(markOf(r))} | ${[...pts, ...drops].join(' <br>') || '(no points)'} |`);
    }
    md.push('');
  }
  md.push('## Appendix: time, tokens and cost per model', '', '| Model | Answers | Errors | Points kept | Points dropped | Time p50 / p95 | Tokens in | Tokens out | Cost | Cost per answer |', '|---|---|---|---|---|---|---|---|---|---|');
  for (const m of models) {
    const rows = rowsByModel.get(m), ms = rows.filter((r) => r.ok).map((r) => r.ms || 0).sort((a, b) => a - b), q = (p) => ((ms[Math.min(ms.length - 1, Math.floor(p * ms.length))] ?? 0) / 1000).toFixed(1);
    const cost = rows.reduce((t, r) => t + (r.cost || 0), 0);
    md.push(`| ${m} | ${rows.length} | ${rows.filter((r) => !r.ok).length} | ${rows.reduce((t, r) => t + (r.points || []).length, 0)} | ${rows.reduce((t, r) => t + (r.dropped || []).length, 0)} | ${q(0.5)} s / ${q(0.95)} s | ${rows.reduce((t, r) => t + (r.usage?.input || 0), 0).toLocaleString('en-IN')} | ${rows.reduce((t, r) => t + (r.usage?.output || 0), 0).toLocaleString('en-IN')} | ${usd(cost)} | ${rows.length ? `$${(cost / rows.length).toFixed(5)}` : '-'} |`);
  }
  return `${md.join('\n')}\n`;
}

export function readRuns(dir, out) {
  const prefix = `observe-${out}-`, rowsByModel = new Map();
  for (const f of readdirSync(dir).filter((x) => x.startsWith(prefix) && x.endsWith('.jsonl')).sort()) {
    rowsByModel.set(f.slice(prefix.length, -'.jsonl'.length), readFileSync(resolve(dir, f), 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l)));
  }
  return rowsByModel;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2), opt = (name, d) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : d; };
  const out = args[0];
  if (!out || out.startsWith('--')) { console.error('usage: node ai-evals/answers-doc.mjs <out> [--dir folder] [--to file.md] [--title "…"]'); process.exit(1); }
  const dir = resolve(opt('dir', new URL('./results/', import.meta.url).pathname));
  const rowsByModel = readRuns(dir, out);
  if (!rowsByModel.size) { console.error(`no observe-${out}-*.jsonl in ${dir}`); process.exit(1); }
  const to = resolve(opt('to', resolve(dir, `observe-${out}-answers.md`)));
  writeFileSync(to, answersDoc({ title: opt('title', `The AI evaluator: every answer of the run "${out}"`), out, rowsByModel, cases: loadCases(loadProblems()) }));
  console.log(`written: ${to}`);
}
